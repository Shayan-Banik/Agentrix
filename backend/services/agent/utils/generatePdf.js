import PDFDocument from "pdfkit";

export const generatePdf = async (data) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margin: 50,
      info: {
        Title: data.title,
        Author: "Agentrix",
        Creator: "Agentrix",
      },
    });

    const chunks = [];

    doc.on("data", (chunk) => {
      chunks.push(chunk);
    });

    doc.on("end", () => {
      const pdfBuffer = Buffer.concat(chunks);
      resolve(pdfBuffer);
    });

    doc.on("error", (error) => {
      reject(error);
    });

    //* Title
    doc
      .font("Helvetica-Bold")
      .fontSize(26)
      .text(data.title, {
        align: "center",
      })
      .fillColor("#111827");

    if (data.subtitle) {
      doc.moveDown(0.5);
    }

    //* subtitle
    doc
      .fontSize(12)
      .text(data.subtitle, {
        align: "center",
      })
      .fillColor("#6B7280");

    doc.moveDown(2);

    //* sections
    data?.sections?.forEach((section) => {
      doc.fontSize(18).text(section.heading).fillColor("#111827");

      doc.moveDown(0.5);

      section?.points?.forEach((point) => {
        doc
          .fontSize(12)
          .text("• " + point, {
            lineGap: 5,
          })
          .fillColor("#374161");
      });

      doc.moveDown(1);
    });

    //* footer
    doc.moveDown(1);

    doc
      .fontSize(10)
      .text("Generated By Agentrix", {
        align: "center",
      })
      .fillColor("#9CA3AF");

    doc.end();
  });
};
